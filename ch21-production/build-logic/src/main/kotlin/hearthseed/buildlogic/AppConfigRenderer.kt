package hearthseed.buildlogic

/** Turns public build properties into the source of a Kotlin `object`. */
object AppConfigRenderer {
    /** Words that suggest a secret: such a value must never ship. */
    private val secretWords = listOf(
        "secret", "password", "token", "apikey", "privatekey", "credential",
    )

    fun render(
        packageName: String,
        objectName: String,
        entries: Map<String, String>,
    ): String {
        entries.keys.forEach { key ->
            require(key.matches(Regex("[a-z][A-Za-z0-9]*"))) { "Bad name: $key" }
            val lower = key.lowercase()
            require(secretWords.none { it in lower }) {
                "app.config.$key looks like a secret; " +
                    "it would ship inside the binary"
            }
        }
        val body = entries.toSortedMap().entries.joinToString("\n") { (k, v) ->
            "    const val ${constantName(k)}${literal(v)}"
        }
        return """
            |// Generated by the generateAppConfig task. Do not edit.
            |package $packageName
            |
            |object $objectName {
            |$body
            |}
            |""".trimMargin()
    }

    /** `apiBaseUrl` becomes `API_BASE_URL`. */
    fun constantName(key: String): String =
        key.replace(Regex("([a-z0-9])([A-Z])"), "$1_$2").uppercase()

    /** Whole numbers become Int, true/false Boolean, the rest String. */
    private fun literal(value: String): String = when {
        value.matches(Regex("-?[0-9]{1,9}")) -> ": Int = $value"
        value == "true" || value == "false" -> ": Boolean = $value"
        else -> ": String = \"" + value.replace("\\", "\\\\")
            .replace("\"", "\\\"").replace("$", "\\$") + "\""
    }
}
